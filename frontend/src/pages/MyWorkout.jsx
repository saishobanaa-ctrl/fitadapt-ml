import { useState, useEffect } from 'react'
import { useNavigate } from 'react-router-dom'
import WorkoutCard from '../components/WorkoutCard'
import ProgressBar from '../components/ProgressBar'

const GOAL_LABELS = {
  'Weight Loss':  '🔥 Weight Loss',
  'Muscle Gain':  '💪 Muscle Gain',
  'Endurance':    '🏃 Endurance',
  'Flexibility':  '🧘 Flexibility',
}

const EXP_LABELS = {
  'Beginner':     '🌱 Beginner',
  'Intermediate': '⚙️ Intermediate',
  'Advanced':     '🏆 Advanced',
}

const EQUIP_LABELS = {
  'None':     '🏠 No Equipment',
  'Minimal':  '🪢 Minimal',
  'Full Gym': '🏋️ Full Gym',
}

export default function MyWorkout() {
  const navigate = useNavigate()
  const [plan, setPlan]             = useState(null)
  const [clusterId, setClusterId]   = useState(null)
  const [completed, setCompleted]   = useState({})
  const [loading, setLoading]       = useState(false)

  // Load plan from sessionStorage (set after prediction)
  useEffect(() => {
    const stored = sessionStorage.getItem('fitadapt_plan')
    const storedCluster = sessionStorage.getItem('fitadapt_cluster')
    if (stored) {
      setPlan(JSON.parse(stored))
      setClusterId(storedCluster)
    }
  }, [])

  const toggleExercise = (index) => {
    setCompleted(prev => ({ ...prev, [index]: !prev[index] }))
  }

  const completedCount = Object.values(completed).filter(Boolean).length
  const totalExercises = plan?.exercises?.length ?? 0
  const allDone = totalExercises > 0 && completedCount === totalExercises

  const resetWorkout = () => {
    setCompleted({})
  }

  if (!plan) {
    return (
      <div style={{ minHeight: '80vh', display: 'flex', alignItems: 'center', justifyContent: 'center' }}>
        <div style={{ textAlign: 'center', maxWidth: 440 }}>
          <div style={{ fontSize: '4rem', marginBottom: '1rem' }}>🤖</div>
          <h1 style={{ fontSize: '1.6rem', fontWeight: 800, fontFamily: "'Space Grotesk', sans-serif", marginBottom: '0.75rem' }}>
            No Workout Plan Yet
          </h1>
          <p style={{ color: 'var(--text-secondary)', marginBottom: '2rem', lineHeight: 1.7 }}>
            Your personalized plan will appear here after the ML pipeline processes your health data.
          </p>
          <button
            id="go-to-predictor-btn"
            className="btn-primary"
            onClick={() => navigate('/predict')}
            style={{ fontSize: '1rem', padding: '0.9rem 2rem' }}
          >
            <span>⚡ Run Health Predictor</span>
          </button>
        </div>
      </div>
    )
  }

  return (
    <div style={{ minHeight: '100vh', padding: '3rem 1.5rem 5rem' }}>
      <div className="container" style={{ maxWidth: 760 }}>

        {/* Page Header */}
        <div style={{ marginBottom: '2rem' }}>
          <div style={{ display: 'flex', alignItems: 'center', gap: '0.75rem', marginBottom: '0.75rem', flexWrap: 'wrap' }}>
            <span className="badge badge-blue">🤖 ML-Recommended Plan</span>
            {clusterId !== null && (
              <span className="badge" style={{ background: 'rgba(167,139,250,0.15)', color: '#a78bfa', border: '1px solid rgba(167,139,250,0.3)' }}>
                👥 Cluster #{clusterId}
              </span>
            )}
          </div>
          <h1
            className="heading-hero"
            style={{ fontSize: 'clamp(1.8rem, 4vw, 2.5rem)', marginBottom: '0.5rem' }}
            id="workout-plan-title"
          >
            {plan.name}
          </h1>
          <p style={{ color: 'var(--text-secondary)', fontSize: '0.9rem' }}>
            Your personalized workout plan — generated by the Random Forest Plan Scorer
          </p>
        </div>

        {/* Plan Metadata */}
        <div className="glass-card" style={{ padding: '1.25rem', marginBottom: '1.5rem', display: 'flex', gap: '1rem', flexWrap: 'wrap' }}>
          <div className="stat-box" style={{ flex: 1, minWidth: 100 }}>
            <div style={{ fontSize: '0.72rem', color: 'var(--text-muted)', textTransform: 'uppercase', letterSpacing: '0.07em', marginBottom: '0.3rem' }}>Goal</div>
            <div style={{ fontWeight: 700, fontSize: '0.9rem' }}>{GOAL_LABELS[plan.goal] || plan.goal || '—'}</div>
          </div>
          <div className="stat-box" style={{ flex: 1, minWidth: 100 }}>
            <div style={{ fontSize: '0.72rem', color: 'var(--text-muted)', textTransform: 'uppercase', letterSpacing: '0.07em', marginBottom: '0.3rem' }}>Level</div>
            <div style={{ fontWeight: 700, fontSize: '0.9rem' }}>{EXP_LABELS[plan.experience_level] || plan.experience_level || '—'}</div>
          </div>
          <div className="stat-box" style={{ flex: 1, minWidth: 100 }}>
            <div style={{ fontSize: '0.72rem', color: 'var(--text-muted)', textTransform: 'uppercase', letterSpacing: '0.07em', marginBottom: '0.3rem' }}>Equipment</div>
            <div style={{ fontWeight: 700, fontSize: '0.9rem' }}>
              {EQUIP_LABELS[plan.equipment] || plan.equipment || '—'}
            </div>
          </div>
          <div className="stat-box" style={{ flex: 1, minWidth: 100 }}>
            <div style={{ fontSize: '0.72rem', color: 'var(--text-muted)', textTransform: 'uppercase', letterSpacing: '0.07em', marginBottom: '0.3rem' }}>Quality Score</div>
            <div style={{ fontWeight: 800, fontSize: '1.2rem', color: 'var(--accent-green)', fontFamily: "'Space Grotesk', sans-serif" }}>
              {plan.quality_score?.toFixed(1)}
            </div>
          </div>
          <div className="stat-box" style={{ flex: 1, minWidth: 100 }}>
            <div style={{ fontSize: '0.72rem', color: 'var(--text-muted)', textTransform: 'uppercase', letterSpacing: '0.07em', marginBottom: '0.3rem' }}>Volume</div>
            <div style={{ display: 'flex', gap: '0.3rem', alignItems: 'center', marginTop: '0.2rem' }}>
              {Array.from({ length: 10 }).map((_, i) => (
                <div key={i} style={{
                  width: 6, height: 14, borderRadius: 3,
                  background: plan.volume_score != null && i < plan.volume_score ? 'var(--accent-cyan)' : 'rgba(255,255,255,0.1)',
                  transition: 'background 0.2s ease',
                }} />
              ))}
            </div>
          </div>
          <div className="stat-box" style={{ flex: 1, minWidth: 100 }}>
            <div style={{ fontSize: '0.72rem', color: 'var(--text-muted)', textTransform: 'uppercase', letterSpacing: '0.07em', marginBottom: '0.3rem' }}>Intensity</div>
            <div style={{ display: 'flex', gap: '0.3rem', alignItems: 'center', marginTop: '0.2rem' }}>
              {Array.from({ length: 10 }).map((_, i) => (
                <div key={i} style={{
                  width: 6, height: 14, borderRadius: 3,
                  background: plan.intensity_score != null && i < plan.intensity_score ? '#f87171' : 'rgba(255,255,255,0.1)',
                  transition: 'background 0.2s ease',
                }} />
              ))}
            </div>
          </div>
        </div>

        {/* Progress Bar */}
        <div style={{ marginBottom: '1.5rem' }}>
          <ProgressBar completed={completedCount} total={totalExercises} />
        </div>

        {/* Controls */}
        <div style={{ display: 'flex', gap: '0.75rem', marginBottom: '1.5rem', flexWrap: 'wrap' }}>
          <button
            id="reset-workout-btn"
            onClick={resetWorkout}
            className="btn-secondary"
            style={{ fontSize: '0.85rem', padding: '0.6rem 1.25rem' }}
          >
            🔄 Reset
          </button>
          <button
            id="run-new-analysis-btn"
            onClick={() => navigate('/predict')}
            className="btn-secondary"
            style={{ fontSize: '0.85rem', padding: '0.6rem 1.25rem' }}
          >
            ⚡ Run New Analysis
          </button>
          {allDone && (
            <span className="badge badge-low" style={{ padding: '0.6rem 1rem', fontSize: '0.85rem' }}>
              🏆 Session Complete!
            </span>
          )}
        </div>

        {/* Exercise List */}
        <div style={{ display: 'flex', flexDirection: 'column', gap: '0.75rem' }}>
          {plan.exercises.map((exercise, i) => (
            <WorkoutCard
              key={i}
              exercise={exercise}
              index={i}
              completed={!!completed[i]}
              onToggle={() => toggleExercise(i)}
            />
          ))}
        </div>

        {/* Completion Banner */}
        {allDone && (
          <div style={{
            marginTop: '2rem', padding: '2rem',
            background: 'linear-gradient(135deg, rgba(52,211,153,0.15), rgba(56,189,248,0.15))',
            border: '1px solid rgba(52,211,153,0.4)',
            borderRadius: 20, textAlign: 'center',
            animation: 'slide-up 0.5s ease',
          }}>
            <div style={{ fontSize: '3rem', marginBottom: '0.75rem' }}>🏆</div>
            <h2 style={{ fontSize: '1.5rem', fontWeight: 800, fontFamily: "'Space Grotesk', sans-serif", color: '#34d399', marginBottom: '0.5rem' }}>
              Workout Complete!
            </h2>
            <p style={{ color: 'var(--text-secondary)', lineHeight: 1.7, maxWidth: 400, margin: '0 auto 1.5rem' }}>
              Outstanding effort! Consistency is what transforms potential into results.
              Come back tomorrow and do it again!
            </p>
            <button
              id="complete-new-analysis-btn"
              className="btn-primary"
              onClick={() => { resetWorkout(); navigate('/predict') }}
              style={{ fontSize: '0.95rem' }}
            >
              <span>🚀 Start New Analysis</span>
            </button>
          </div>
        )}

        {/* ML Info Note */}
        <div style={{
          marginTop: '2rem', padding: '1rem 1.25rem',
          background: 'rgba(56,189,248,0.05)', border: '1px solid rgba(56,189,248,0.15)',
          borderRadius: 12, fontSize: '0.82rem', color: 'var(--text-muted)', lineHeight: 1.6,
        }}>
          <strong style={{ color: 'var(--accent-cyan)' }}>🤖 How this plan was selected: </strong>
          Your biometrics were processed through a <strong>K-Means clustering model</strong> (k=5, evaluated with Silhouette Score)
          to assign you to Cluster #{clusterId}. A <strong>Random Forest Regressor</strong> then scored all 13 workout templates
          against your cluster profile — this plan achieved the highest predicted quality score of{' '}
          <strong style={{ color: 'var(--accent-green)' }}>{plan.quality_score?.toFixed(1)}/100</strong>.
        </div>
      </div>
    </div>
  )
}
